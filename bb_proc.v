/*
 *  Baseband Processor (Refactored for FPGA PIE Decoder Architecture)
 *
 *  Must read EPC Gen2 UHF RFID protocols
 *
 *  ARCHITECTURE CHANGE (FPGA Mode):
 *  --------------------------------
 *  The original ASIC design used an analog delay element to produce
 *  `clk_dpie` (a phase-shifted copy of the PIE signal) for clocking
 *  `cmd_buf`.  On the FPGA there is no delay line, so this module now
 *  instantiates a fully digital `pie_decoder` that:
 *    1. Runs on the 5 MHz system clock
 *    2. Uses the measured `tari_width` from `fs_detector` for dynamic
 *       clock-recovery (midpoint strobe at 50% of Tari)
 *    3. Outputs `pie_decoded_bit` (data) and `pie_dec_clk` (reconstructed
 *       clock) that replace the raw `pie_code`/`clk_dpie` for cmd_buf,
 *       CRG, and CRC-5 paths
 *
 *  All of the input and output signals depend on your whole RFID Tag design
 *  In this case, we use the delayed PIE code to clock the received PIE code.
 *  So we should input PIE code (pie_code) and delayed PIE code (clk_dpie)
 *  we use the clock signal in 200 KHz generated by Multivibrator to generate
 *  the clock signal in BLF. (clk_200K)
 *  rst is generated by POR circuit to reset the baseband processor. (rst)
 *  output the backscattered data to control the Backscatter circuit. (bs_data)
 *
 *  Debug outputs: brain_state, ila_fs, dbg_pulse_width from fs_detector via rx.
 *  New: tari_width[15:0] from fs_detector for ILA monitoring.
 */


`timescale 1us / 1ns


module bb_proc
(
output wire bs_data,
output wire package_complete,
output wire crc_check_pass,
output wire en_tx,
output wire [2:0]  brain_state,       // fs_detector state monitor
output wire        ila_fs,            // frame-sync flag for ILA
output wire [15:0] dbg_pulse_width,   // pulse width measurement
output wire [3:0]  cmd_state,         // cmd_proc EPC Gen2 tag FSM present state
output wire [15:0] tari_width,        // measured Tari period (5 MHz ticks) for ILA
input wire clk_200K,
input wire pie_code,
input wire clk_dpie,
input wire clk,                        // 5 MHz system clock for fs_detector
input wire rst,
input wire debug_switch
);


wire clk_crc5;
wire clk_crc16;
wire clk_blf;
wire clk_cp;
wire clk_prng;
wire clk_frm;
wire clk_fm0;
wire clk_mil;
wire clk_mem;
wire rst_n;
wire rst_for_new_package;
wire rst_crc16;
wire start_working;
wire dr;
wire [1:0]m;
wire en_crc5;
wire en_crc16;
wire en_2nd_clk_cp;
wire en_prng_idol;
wire en_prng_act;
wire en_if;
wire packet_complete_sync;
wire en_crc16_for_rpy;
wire reply_complete;
wire rd_complete;
wire bs_complete;
wire [7:0]cmd;
wire [51:0]param;
wire [15:0]crc_16;
wire reply_data;
wire trext;
wire [18:0]addr;
wire [15:0]prn;
wire rd_data;
wire pre_p_complete;
wire p_complete;
wire [5:0]A;
wire [15:0]Q;
wire CEN;

// --- PIE decoder outputs ---
wire pie_decoded_bit;     // decoded data bit from PIE decoder
wire pie_bit_strobe;      // single-cycle valid strobe
wire pie_dec_clk;         // reconstructed clock for cmd_buf

// --- Internal sync wire from rx/fs_detector ---
wire sync_internal;       // frame-sync valid (= ila_fs)


// --- Clock/Reset Generator ---
// NOTE: In FPGA mode, CRG receives the PIE-decoded clock and data
//       instead of the raw analog clk_dpie/pie_code.
crg crg_1
(
.clk_crc5(clk_crc5),
.clk_crc16(clk_crc16),
.clk_blf(clk_blf),
.clk_cp(clk_cp),
.clk_prng(clk_prng),
.clk_frm(clk_frm),
.clk_fm0(clk_fm0),
.clk_mil(clk_mil),
.clk_mem(clk_mem),
.rst_n(rst_n),
.clk_200K(clk_200K),
.clk_dpie(pie_dec_clk),             // CHANGED: reconstructed clock from PIE decoder
.pie_code(pie_decoded_bit),          // CHANGED: decoded bit from PIE decoder
.frame_sync(sync_internal),          // frame-sync valid for rst_for_new_package
.rst(rst),
.rst_for_new_package(rst_for_new_package),
.rst_crc16(rst_crc16),
.start_working(start_working),
.dr(dr),
.m(m),
.en_crc5(en_crc5),
.en_crc16(en_crc16),
.en_2nd_clk_cp(en_2nd_clk_cp),
.en_prng_idol(en_prng_idol),
.en_prng_act(en_prng_act),
.en_tx(en_tx),
.en_if(en_if),
.packet_complete_sync(packet_complete_sync),
.en_crc16_for_rpy(en_crc16_for_rpy),
.reply_complete(reply_complete),
.rd_complete(rd_complete),
.bs_complete(bs_complete)
);


// --- RX (including Frame-Sync Detector, CRC-5, CRC-16 and Command Buffer) ---
// fs_detector still receives raw pie_code on the 5 MHz clock domain.
// CRC-5/CRC-16 and cmd_buf now receive PIE-decoded data and clock.
rx rx_1
(
.cmd(cmd),
.param(param),
.package_complete(package_complete),
.crc_check_pass(crc_check_pass),
.crc_16(crc_16),
.en_crc5(en_crc5),
.en_crc16(en_crc16),
.brain_state(brain_state),
.ila_fs(ila_fs),
.dbg_pulse_width(dbg_pulse_width),
.tari_width(tari_width),              // measured Tari from fs_detector
.pie_code(pie_code),                   // raw PIE to fs_detector
.decoded_bit(pie_decoded_bit),         // ADDED: decoded bit from PIE decoder
.clk_dpie(pie_dec_clk),               // CHANGED: reconstructed clock → cmd_buf
.clk_crc5(clk_crc5),
.clk_crc16(clk_crc16),
.clk(clk),                            // 5 MHz system clock
.rst_n(rst_n),
.rst_for_new_package(rst_for_new_package),
.rst_crc16(rst_crc16),
.reply_data(reply_data),
.en_crc16_for_rpy(en_crc16_for_rpy)
);

// Grab sync from ila_fs (which mirrors rx/fs_detector sync)
assign sync_internal = ila_fs;


// --- PIE Decoder (NEW for FPGA mode) ---
// Decodes PIE symbols using the 5 MHz clock and fs_detector's tari_width.
// Replaces the ASIC's analog clk_dpie delay-line approach.
pie_decoder pie_dec_1
(
.bit_val(pie_decoded_bit),
.bit_strobe(pie_bit_strobe),
.dec_clk(pie_dec_clk),
.clk(clk),
.rst_n(rst_n),
.rfid_in(pie_code),
.sync(sync_internal),
.tari_width(tari_width),
.package_complete(package_complete)
);


// --- Synchronizer (conventional two flip-flop) ---
two_dff_sync two_dff_sync_1
(
.data_out(packet_complete_sync),
.clk_ad(pie_dec_clk),                 // CHANGED: from clk_dpie to pie_dec_clk
.clk_bd(clk_blf),
.rst_n(rst_n),
.data_in(package_complete)
);


// --- Command Processor ---
cmd_proc cmd_proc_1
(
.reply_data(reply_data),
.reply_complete(reply_complete),
.dr(dr),
.m(m),
.trext(trext),
.en_2nd_clk_cp(en_2nd_clk_cp),
.en_tx(en_tx),
.en_prng_idol(en_prng_idol),
.en_prng_act(en_prng_act),
.en_crc16_for_rpy(en_crc16_for_rpy),
.en_if(en_if), 
.addr(addr),
.debug_state(cmd_state),              // expose EPC Gen2 FSM state to top level
.clk_cp(clk_cp),
.clk_frm(clk_frm),
.rst_n(rst_n),
.rst_for_new_package(rst_for_new_package),
.cmd(cmd),
.param(param),
.prn(prn),
.crc_check_pass(crc_check_pass),
.rd_data(rd_data),
.pre_p_complete(pre_p_complete),
.p_complete(p_complete),
.rd_complete(rd_complete),
.debug_switch(debug_switch)
);


// --- Pseudo Random Number Generator ---
prng prng_1
(
.prn(prn),
.clk_prng(clk_prng),
.rst_n(rst_n)
);


// --- Memory Interface ---
mem_if mem_if_1
(
.rd_data(rd_data),
.rd_complete(rd_complete),
.A(A),
.CEN(CEN),
.addr(addr),
.Q(Q),
.clk_if(clk_mem),
.rst_for_new_package(rst_for_new_package)
);


// --- ROM (64 words, 16 bits per word) ---
rom_64x16 rom_64x16_1
(
.Q(Q),
.CLK(clk_200K),   // Use clk_200K as the clock for ROM
.CEN(CEN),
.A(A)
);


// --- TX (including Frame Generator, FM0 Encoder, Miller Encoder) ---
tx tx_1
(
.bs_data(bs_data),
.pre_p_complete(pre_p_complete),
.p_complete(p_complete),
.bs_complete(bs_complete),
.clk_blf(clk_blf),
.clk_frm(clk_frm),
.clk_fm0(clk_fm0),
.clk_mil(clk_mil),
.rst_for_new_package(rst_for_new_package),
.reply_data(reply_data),
.crc_16(crc_16),
.m(m),
.trext(trext),
.reply_complete(reply_complete),
.en_crc16_for_rpy(en_crc16_for_rpy),
.start_working(start_working)
);


endmodule
